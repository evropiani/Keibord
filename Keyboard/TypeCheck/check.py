#!/usr/bin/env python3
"""Type-check (and with --test, unit-test) the keyboard extension's sources on Linux.

Copies Keyboard/Sources/*.swift plus the Shared files the keyboard uses into
Keyboard/TypeCheck/Sources/KeyboardCheck/Generated/, rewriting ObjC-only syntax (no ObjC runtime on Linux):
`@objc` is dropped and `#selector(x)` becomes `sel(x)`, which still type-checks the referenced method.
Shared files that need CryptoKit/Security are replaced by Sources/KeyboardCheck/SharedStubs.swift.

    python3 Keyboard/TypeCheck/check.py            # swift build
    python3 Keyboard/TypeCheck/check.py --test     # swift test

The UIKit stand-in only covers what the keyboard uses; a missing member there is a gap in the stub, not
necessarily a bug. Real-world caveats (ObjC exposure, availability, behaviour) still need the Xcode build.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(HERE, "Sources", "KeyboardCheck", "Generated")
SHARED = ["Shared/Support.swift", "Shared/KeibordStore.swift", "Shared/AppGroup.swift"]


def generate():
    shutil.rmtree(OUT, ignore_errors=True)
    os.makedirs(OUT)
    keyboard = sorted("Keyboard/Sources/" + f for f in os.listdir(os.path.join(REPO, "Keyboard/Sources")) if f.endswith(".swift"))
    for rel in keyboard + SHARED:
        with open(os.path.join(REPO, rel)) as f:
            src = f.read()
        src = re.sub(r"@objc\s+", "", src)
        src = src.replace("#selector(", "sel(")
        with open(os.path.join(OUT, os.path.basename(rel)), "w") as f:
            f.write("// Generated by Keyboard/TypeCheck/check.py from %s; do not edit.\n" % rel + src)


def main():
    generate()
    command = "test" if "--test" in sys.argv else "build"
    scratch = os.environ.get("KEYBOARD_CHECK_SCRATCH", os.path.join(HERE, ".build"))
    env = dict(os.environ)
    # KeibordStore falls back to Application Support (no app group on Linux): keep test files out of $HOME.
    env["XDG_DATA_HOME"] = tempfile.mkdtemp(prefix="keyboard-check-")
    sys.exit(subprocess.call(["swift", command, "--package-path", HERE, "--scratch-path", scratch], env=env))


if __name__ == "__main__":
    main()
